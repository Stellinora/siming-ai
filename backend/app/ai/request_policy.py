"""Wire defaults identified by endpoint and protocol, never by display/model names.

The Android projection is generated by export-mobile-prompt-contract.py.
Unknown endpoints keep their explicit request settings and server defaults.
"""
from __future__ import annotations

from copy import deepcopy
from urllib.parse import urlparse

MODEL_REQUEST_POLICY = {
    "explicit_thinking_fields": [
        "thinking", "reasoning", "reasoning_effort", "enable_thinking", "thinking_budget",
    ],
    "endpoints": {
        "api.deepseek.com": {
            "chat_completions": {
                "non_thinking_modes": ["text", "cataloging", "tool_recovery"],
                "non_thinking_body": {"thinking": {"type": "disabled"}},
                "supports_tool_choice": False,
            },
            "responses": {
                "non_thinking_modes": ["text", "cataloging", "tool_recovery"],
                "non_thinking_body": {"reasoning": {"effort": "none"}},
                "supports_tool_choice": False,
            },
        },
        "api.siliconflow.cn": {
            "chat_completions": {
                "non_thinking_modes": ["cataloging"],
                "non_thinking_body": {"enable_thinking": False},
                "supports_tool_choice": True,
            },
        },
        "generativelanguage.googleapis.com": {
            "chat_completions": {
                "non_thinking_modes": [],
                "non_thinking_body": {},
                "supports_tool_choice": False,
            },
        },
    },
}


def endpoint_request_policy(base_url: str | None, protocol: str) -> dict:
    try:
        endpoint = urlparse((base_url or "").strip())
        if endpoint.scheme != "https" or endpoint.port not in (None, 443):
            return {}
        host = (endpoint.hostname or "").rstrip(".")
    except ValueError:
        return {}
    return MODEL_REQUEST_POLICY["endpoints"].get(host, {}).get(protocol, {})


def non_thinking_defaults(
    base_url: str | None, protocol: str, mode: str, extra_body: dict | None,
) -> dict:
    if any(key in (extra_body or {}) for key in MODEL_REQUEST_POLICY["explicit_thinking_fields"]):
        return {}
    policy = endpoint_request_policy(base_url, protocol)
    if mode not in policy.get("non_thinking_modes", []):
        return {}
    return deepcopy(policy.get("non_thinking_body", {}))


def provider_tool_choice(
    base_url: str | None, protocol: str, requested: str | dict | None,
) -> str | dict | None:
    if not endpoint_request_policy(base_url, protocol).get("supports_tool_choice", True):
        return None
    return requested


def provider_extra_body(
    extra_body: dict | None, base_url: str | None, protocol: str = "chat_completions",
    *, text_only: bool = False,
) -> dict | None:
    metadata = extra_body or {}
    mode = "cataloging" if metadata.get("moshu_task_type") == "cataloging" else (
        "text" if text_only else "tools"
    )
    payload = {
        key: value for key, value in metadata.items()
        if not key.startswith(("moshu_", "local_cli_"))
    }
    return {**non_thinking_defaults(base_url, protocol, mode, payload), **payload} or None
